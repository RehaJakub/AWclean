import { readdir, mkdir, writeFile, readFile } from "node:fs/promises";
import { join, relative, parse } from "node:path";
import sharp from "sharp";
const root = "public/images";
interface ImageVariant {
  width: number;
  height: number;
  srcSet: string;
}
const manifest: Record<string, ImageVariant> = {};
const used = new Set<string>();
async function collect(directory: string): Promise<void> {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) await collect(file);
    else if (
      /\.tsx?$/.test(file) &&
      !["imageVariants.ts", "photos.ts"].includes(entry.name)
    ) {
      for (const match of (await readFile(file, "utf8")).matchAll(
        /"(\/images\/[^"\n]+\.webp)"/g,
      ))
        used.add(match[1]);
    }
  }
}
await collect("src");
async function visit(directory: string): Promise<void> {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === "responsive") continue;
    const file = join(directory, entry.name);
    if (entry.isDirectory()) {
      await visit(file);
      continue;
    }
    if (!/\.(webp|jpe?g|png)$/i.test(entry.name)) continue;
    const source = `/${file.slice("public/".length)}`;
    if (!used.has(source) && !source.startsWith("/images/press/")) continue;
    const metadata = await sharp(file).metadata();
    if (!metadata.width || !metadata.height) continue;
    const rel = relative(root, file);
    const variants: string[] = [];
    for (const width of [480, 960, 1440].filter(
      (size) => size < metadata.width!,
    )) {
      const output = join(
        root,
        "responsive",
        parse(rel).dir,
        `${parse(rel).name}-${width}.webp`,
      );
      await mkdir(parse(output).dir, { recursive: true });
      await sharp(file).resize({ width }).webp({ quality: 80 }).toFile(output);
      variants.push(`/${output.slice("public/".length)} ${width}w`);
    }
    variants.push(`${source} ${metadata.width}w`);
    manifest[source] = {
      width: metadata.width,
      height: metadata.height,
      srcSet: variants.join(", "),
    };
  }
}
await visit(root);
await writeFile(
  "src/data/imageVariants.ts",
  `// Generated by npm run images. Sources remain in public/images.\nexport interface ImageVariant { width: number; height: number; srcSet: string; }\nexport const imageVariants: Record<string, ImageVariant> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(
  `Vygenerovány responzivní varianty pro ${Object.keys(manifest).length} obrázků.`,
);
